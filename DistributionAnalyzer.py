import json
from collections import Counter
import os
from Naming.NamingAnalyzer import NamingAnalyzer
from Spacing.SpacingAnalyzer import SpacingAnalyzer

class DistributionAnalyzer:
    """
    Analyzes the distribution of correct answers (Ground Truth) generated by the underlying Analyzers
    (Spacing, Naming) and compiles a detailed statistical report with counts and percentages.
    """
    def __init__(self, spacingAnalyzer: SpacingAnalyzer = None, namingAnalyzer: NamingAnalyzer = None):
        codebase_path = os.path.join(os.path.dirname(__file__), "Codebase", "downloads")
        self.spacingAnalyzer= SpacingAnalyzer(codebase_path=codebase_path, max_token_limit=250000, max_results_per_question=10000) if spacingAnalyzer is None else spacingAnalyzer
        self.namingAnalyzer= NamingAnalyzer(codebase_path=codebase_path, max_token_limit=250000, max_results_per_question=20000) if namingAnalyzer is None else namingAnalyzer
        self.analyzers = [self.spacingAnalyzer, self.namingAnalyzer]

    def analyze(self, output_path: str = "answer_distribution_report.json"):
        """
        Executes the analysis on all available question methods, calculates answer distributions,
        and saves the results to a formatted JSON file ("answer_distribution_report.json" by default).

        The method iterates through all registered analyzers, executes methods starting with 'question_',
        collects the ground truth data, sorts the answer distribution by frequency (descending),
        and exports the statistics.

        Args:
            output_path (str, optional): The file path where the JSON report should be saved.
        """
        print(f"\n{'='*60}")
        print("ANALISI DISTRIBUZIONE RISPOSTE (GROUND TRUTH)")
        print(f"{'='*60}")

        all_stats = {}

        for analyzer in self.analyzers:
            for method_name in dir(analyzer):
                
                if not method_name.startswith("question_"):
                    continue
                
                q_id = method_name.replace("question_", "")
                
                method = getattr(analyzer, method_name)
                
                try:
                    print(f"Analisi in corso: {q_id}...", end="\r")
                    results = method()
                    print(f"Analisi completata: {q_id}   ")
                    
                    if not results:
                        all_stats[q_id] = {"status": "NESSUN RISULTATO"}
                        continue

                    answers = []
                    for item in results:
                        if isinstance(item, tuple) and len(item) >= 2:
                            answers.append(str(item[1]))
                        else:
                            print(f"[WARN] {q_id}: Formato dati imprevisto: {item}")

                    total = len(answers)
                    counts = Counter(answers)
                    
                    sorted_counts = sorted(counts.items(), key=lambda x: x[1], reverse=True)

                    formatted_distribution = {}
                    
                    for answer_key, count in sorted_counts:
                        percentage = (count / total) * 100 if total > 0 else 0
                        formatted_distribution[answer_key] = f"{count}, {percentage:.1f}%"

                    all_stats[q_id] = {
                        "total_samples": total,
                        "distribution": formatted_distribution
                    }

                except Exception as e:
                    print(f"[ERR] Errore analizzando {q_id}: {e}")
                    all_stats[q_id] = {"error": str(e)}

        # --- SALVATAGGIO JSON ---
        if output_path:
            try:
                with open(output_path, 'w', encoding='utf-8') as f:
                    json.dump(all_stats, f, indent=4, ensure_ascii=False)
                print(f"Report JSON salvato in: {output_path}")
            except Exception as e:
                print(f"Impossibile salvare il JSON: {e}")