import json
import random
import os
from typing import List, Dict, Any, Optional
from DataClassesDefiner import Question, Answer, BenchmarkItem
from DistractorGenerator import DistractorGenerator
from Naming.NamingDistractorGenerator import NamingDistractorGenerator
from Spacing.SpacingDistractorGenerator import SpacingDistractorGenerator

class BenchmarkSystem:
    """
    Orchestrates the generation of a unified benchmark file from a static JSON dataset.
    It implements a balanced sampling strategy (80/20 "Coinflip") to ensure high variance 
    in the correct answers selected for the test set, preventing the benchmark from being dominated 
    by common coding styles (e.g., always 4 spaces).
    """
    
    def __init__(self, dataset_path: str):
        """
        Initializes the system by loading the dataset and configuring the distractor generators.

        Args:
            dataset_path (str): The file path to the 'master_dataset.json' generated by the DatasetGenerator.
        """
        self.dataset_path = dataset_path
        self.dataset = self._load_dataset()
        
        self.distractor_generators: Dict[str, DistractorGenerator] = {
            "naming": NamingDistractorGenerator(),
            "spacing": SpacingDistractorGenerator(),
        }

        self.question_configs = {
            # --- SPACING ---
            "S01": "In variable definitions within the file, how many spaces are used to separate tokens?",
            "S02": "In control structure conditions, how many spaces are used to separate tokens?",
            "S03": "In function argument lists, how many spaces are used before the comma?",
            "S04": "In function argument lists, how many spaces are used after the comma?",
            "S05": "How many blank lines are there after a function definition?",
            "S06": "What is the maximum length of a line of code (excluding comments and docstrings)?",
            "S07": "How many spaces are used for code indentation?",
            "S08": "How many blank lines are there before a comment?",
            "S09": "How many blank lines are there after a comment?",
            "S10": "How many blank lines are there after each import or import block?",
            "S11": "How many blank lines are there after a class definition?",
            "S12": "How many blank lines are there after a constant definition or block of constants?",
            "S13": "Looking at this code snippet: \n\n{0}\n\n, which of the following argument spacing strategies is used?",
            
            # --- NAMING ---
            "N01": "How many 'snake_case' names are present in this file?",
            "N02": "How many 'camelCase' names are present in this file?",
            "N03": "How many 'PascalCase' names are present in this file?",
            "N04": "What is the most frequently used naming convention in this file?",
            "N05": "Which naming convention is used for the name '{0}'?",
            "N06": "Does the name '{0}' follow a standard naming convention (snake_case, camelCase, or PascalCase)?",
            "N07": "How many names do not follow a standard naming convention?",
            "N08": "Does the constant name '{0}' use an underscore?",
            "N09": "What is the length of the longest name found in the file?",
        }

    def _load_dataset(self) -> List[Dict]:
        if not os.path.exists(self.dataset_path):
            raise FileNotFoundError(f"Dataset non trovato in: {self.dataset_path}")
        with open(self.dataset_path, 'r', encoding='utf-8') as f:
            return json.load(f)

    def _resolve_dynamic_answer(self, entry: Dict, q_id: str):
        """
        Determines the specific correct answer for a given file and question ID.

        - For **Static Questions** (e.g., S01 - spaces count), it retrieves the pre-calculated value directly.
        - For **Dynamic Questions** (e.g., N05 - naming convention of a specific var), it randomly selects 
          a raw data point (e.g., a specific variable name from `_raw_names_snake`) and calculates the answer on the fly.

        Args:
            entry (Dict): The dataset entry for a specific file.
            q_id (str): The question ID (e.g., "S01", "N05").

        Returns:
            Tuple[Any, Any]: A tuple containing (FinalAnswerValue, ExtraDataForTemplate). 
                             Returns (None, None) if data is missing.
        """
        answers = entry["answers"]

        # --- Domande Statiche ---
        if q_id not in ["N05", "N06", "N08", "S13"]:
            if q_id in answers and answers[q_id] is not None:
                return answers[q_id], None
            return None, None

        # --- Domande Dinamiche ---
        
        # N05: Convenzione di un nome specifico
        if q_id == "N05":
            pool = []
            # Raccogli tutti i nomi disponibili
            if "_raw_names_snake" in answers: pool.extend([(n, "snake_case") for n in answers["_raw_names_snake"]])
            if "_raw_names_camel" in answers: pool.extend([(n, "camelCase") for n in answers["_raw_names_camel"]])
            if "_raw_names_pascal" in answers: pool.extend([(n, "PascalCase") for n in answers["_raw_names_pascal"]])
            
            if not pool: return None, None
            name, convention = random.choice(pool)
            return convention, name # La risposta è "snake_case", l'extra è "my_var"

        # N06: Standard vs Non Standard
        if q_id == "N06":
            # Qui peschiamo da TUTTI i nomi (anche quelli 'other')
            pool = answers.get("_raw_all_names", [])
            if not pool: return None, None
            name = random.choice(pool)
            
            # Logica booleana is_standard
            is_std = (name[0].isupper() and "_" not in name) or \
                     ("_" in name and name.islower()) or \
                     (name[0].islower() and any(c.isupper() for c in name) and "_" not in name)
            
            return str(is_std).lower(), name

        # N08: Costanti con underscore
        if q_id == "N08":
            pool = answers.get("_raw_constants", [])
            if not pool: return None, None
            name = random.choice(pool)
            val = "true" if "_" in name else "false"
            return val, name

        # S13: Wrapping Strategy
        if q_id == "S13":
            pool = answers.get("_raw_S13", [])
            if not pool: return None, None
            item = random.choice(pool) # item è {'strategy': '...', 'snippet': '...'}
            
            strat = item['strategy']
            # Mappa strategia -> testo leggibile (Risposta corretta)
            label = "Mixed strategy (some on new lines, others not)"
            if strat == "same_line": 
                label = "All arguments are on the same line"
            elif strat == "newline_every_arg": 
                label = "Every argument is on a new line"
            
            return label, item['snippet']

        return None, None

    def _select_diverse_samples(self, question_id: str, target_count: int) -> List[Dict]:
        """
        Selects a target number of file samples for a specific question, applying a heuristic to maximize answer diversity.

        **The 80/20 Coinflip Logic:**
        To avoid homogeneity (e.g., 20 files all using "snake_case"), the method tracks selected answers.
        If a candidate file yields an answer that is *already present* in the selection pool:
        - There is an **80% probability** of skipping this file (to search for a rarer answer).
        - There is a **20% probability** of keeping it (fallback to ensure the target count is reached).

        Args:
            question_id (str): The ID of the question to sample for.
            target_count (int): The number of samples required.

        Returns:
            List[Dict]: A list of dictionaries containing the file path, the resolved answer, and extra data.
        """
        # 1. Filtra i candidati (tutti i file che hanno dati per questa domanda)
        candidates = []
        for entry in self.dataset:
            # Controllo esistenza dati
            if question_id in ["N05", "N06", "N08", "S13"]:
                # Per le dinamiche controlliamo se ci sono i dati grezzi necessari
                has_data = False
                if question_id == "S13" and entry["answers"].get("_raw_S13"): has_data = True
                elif question_id == "N08" and entry["answers"].get("_raw_constants"): has_data = True
                elif question_id in ["N05", "N06"] and entry["answers"].get("_raw_all_names"): has_data = True
                
                if has_data: candidates.append(entry)
            else:
                # Per le statiche basta che la chiave esista e non sia None
                if entry["answers"].get(question_id) is not None:
                    candidates.append(entry)

        random.shuffle(candidates)

        selected_samples = []
        seen_answers = [] # Qui salviamo le risposte finali (es. "4.0", "snake_case")

        for entry in candidates:
            if len(selected_samples) >= target_count:
                break

            # Risolviamo la risposta per questo file
            # (Per le dinamiche, questo "pesca" un nome a caso ORA)
            final_answer_val, extra_data = self._resolve_dynamic_answer(entry, question_id)
            
            if final_answer_val is None:
                continue

            # --- LOGICA COINFLIP 80/20 ---
            # Se abbiamo già selezionato un file che ha QUESTA STESSA RISPOSTA
            if final_answer_val in seen_answers:
                # Generiamo probabilità
                chance = random.random()
                if chance < 0.80:
                    # 80% di probabilità di SCARTARE questo duplicato e cercare varietà
                    continue
                # 20% di probabilità di accettarlo comunque (per non bloccarci se i dati sono omogenei)
            
            # Accettato
            selected_samples.append({
                "file_path": entry["file_path"],
                "answer_val": final_answer_val,
                "extra_data": extra_data
            })
            seen_answers.append(final_answer_val)

        return selected_samples

    def generate_benchmark(self, output_path: str, target_count_per_question: int = 10):
        """
        Generates the final benchmark JSON file containing questions, correct answers, and distractors.

        It iterates through all defined question templates (S01-S13, N01-N09), selects diverse samples 
        using `_select_diverse_samples`, generates plausible distractors using the appropriate generator 
        (Spacing or Naming), and compiles the final list of items.

        Args:
            output_path (str): The file path where the benchmark JSON will be saved.
            target_count_per_question (int, optional): The number of questions to generate per template ID. Defaults to 10.
        """

        if os.path.exists(output_path):
            print(f"[INFO] Esiste già un benchmark in {output_path}. Salto la generazione.\n")
            return

        print(f"Generazione benchmark in: {output_path}...")
        
        benchmark_items = []

        for q_id, template in self.question_configs.items():
            
            # Seleziona n campioni "variegati"
            samples = self._select_diverse_samples(q_id, target_count=target_count_per_question)
            
            category = "spacing" if q_id.startswith("S") else "naming"
            generator = self.distractor_generators.get(category)

            for i, sample in enumerate(samples):
                file_path = sample["file_path"]
                correct_val = sample["answer_val"]
                extra_data = sample["extra_data"]
                
                # Formattazione testo domanda
                final_text = template
                if extra_data:
                    # Se extra_data è molto lungo (es. snippet S13), attenzione al format
                    final_text = template.format(extra_data)

                try:
                    correct_answer_obj = Answer(text=correct_val, is_correct=True)
                    
                    # Proxy per distrattori
                    proxy_q = Question(
                        id=q_id, 
                        category=category, 
                        text_template=final_text, 
                        target_files=[file_path], 
                        correct_answer_values=[correct_val]
                    )

                    distractors = generator.generate(correct_answer_obj, proxy_q)
                    
                    if not distractors:
                        continue

                    # Item Finale
                    full_id = f"{q_id}_{i+1}"
                    
                    final_q_obj = Question(
                        id=full_id,
                        category=category,
                        text_template=final_text,
                        target_files=[file_path],
                        correct_answer_values=[correct_val],
                        extra_data=[extra_data] if extra_data else None
                    )

                    item = BenchmarkItem(
                        question=final_q_obj,
                        correct_answer=correct_answer_obj,
                        distractors=distractors
                    )
                    
                    item_dict = item.to_dict()
                    item_dict["target_file"] = file_path
                    item_dict["question_template"] = template
                    item_dict["choosen_item"] = extra_data

                    benchmark_items.append(item_dict)

                except Exception as e:
                    print(f"[ERR] {full_id}: {e}")
                    continue

        # Salvataggio
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(benchmark_items, f, indent=2, ensure_ascii=False)
        
        print(f" Benchmark completato! Totale item: {len(benchmark_items)}\n")

    def get_benchmark_items(self, benchmark_path: str) -> List[Dict]:
        """
        Loads an existing benchmark dataset from a JSON file.

        Args:
            benchmark_path (str): The path to the benchmark JSON file.

        Returns:
            List[Dict]: The list of benchmark items loaded from the file.
        """
        with open(benchmark_path, 'r', encoding='utf-8') as f:
            benchmark_items = json.load(f)
        return benchmark_items